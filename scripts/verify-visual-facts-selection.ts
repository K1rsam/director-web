import assert from 'node:assert/strict';
import {selectAssetVisualFacts} from '../lib/asset-visual-facts-selection';
import type {VisualFact} from '../lib/asset-visual-facts-contract';
const fact=(attribute:string,value:string,versionKey?:string):VisualFact=>({id:attribute+value,subjectKey:'person',attribute,value,versionKey,scope:versionKey?'STATE':'STABLE',quote:value,chunkId:'source',startLine:1,endLine:1});
const facts=[fact('hair.color','红色'),fact('hair.length','长发','person'),fact('clothing','甲板装','person'),fact('clothing','战斗服','battle'),fact('injury.rightHand','右手受伤','injured'),fact('hair.length','短发','short'),{...fact('hair.color','蓝色'),subjectKey:'other'}];
const versions=[{key:'person'},{key:'battle',fromKey:'person'},{key:'injured',fromKey:'battle'},{key:'short',fromKey:'injured'}];
const base=selectAssetVisualFacts('person','person',facts,versions).facts;
assert.deepEqual(base.map(f=>f.value),['红色','长发','甲板装']);
const child=selectAssetVisualFacts('person','short',facts,versions).facts;
assert.deepEqual(child.map(f=>f.value),['红色','战斗服','右手受伤','短发']);
assert.equal(child.some(f=>f.subjectKey==='other'),false);
assert.throws(()=>selectAssetVisualFacts('person','battle',facts,[{key:'battle',fromKey:'injured'},{key:'injured',fromKey:'battle'}]),/循环/);
const unknown={...fact('state','戴眼镜'),scope:'STATE' as const};
const unresolved=selectAssetVisualFacts('person','person',[unknown],versions);
assert.equal(unresolved.facts.length,0);assert.equal(unresolved.issues.length,1);
const transition={...fact('hair.length','长发→短发','short'),scope:'TRANSITION' as const};
const changed=selectAssetVisualFacts('person','short',[...facts.filter(f=>f.versionKey!=='short'),transition],versions).facts;
assert.ok(changed.some(f=>f.scope==='TRANSITION'));assert.equal(changed.some(f=>f.value==='长发'),false);
console.log('PASS: identity ownership, parent/grandparent inheritance, outfit and haircut overrides, unresolved version blocks and reference cycles.');
