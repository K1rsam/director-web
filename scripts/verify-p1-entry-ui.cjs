const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async function verifyP1Entry({page,context,root,output}) {
  const source='第一集\n1-1 门厅 内 日\n甲：aaa。\n甲把钥匙递给乙。\n';
  await page.goto(root+'/projects/new');
  await page.locator('[name=script]').setInputFiles({name:'paired-original.txt',mimeType:'text/plain',buffer:Buffer.from(source)});
  await page.getByText('让其他 AI 整理：复制材料与接收回复',{exact:true}).click();
  await page.getByRole('button',{name:'生成外部整理材料',exact:true}).click();
  const material=page.getByRole('textbox',{name:'发给外部 AI 的完整材料'});
  await material.waitFor();
  const text=await material.inputValue();
  assert(text.includes('甲：aaa。'));
  const sourceVersion=text.match(/^SOURCE ([a-f0-9]{64})$/m)[1];
  const reply=`FIDELITY-TEXT/1\nSOURCE ${sourceVersion}\nBODY B000001 B000004 1 1\nEND`;
  await page.locator('[name=cleaningMode]').selectOption('direct');
  await page.locator('[name=originalScript]').setInputFiles({name:'paired-original.txt',mimeType:'text/plain',buffer:Buffer.from(source)});
  await page.getByRole('tab',{name:'粘贴文本'}).click();
  await page.locator('[name=scriptText]').fill(reply);
  await page.locator('[name=title]').fill('外部配对入口验收-'+Date.now());
  await page.getByRole('button',{name:'预览与校验剧本'}).click();
  await page.getByRole('heading',{name:'程序初检完成 · 请确认导入'}).waitFor();
  assert((await page.locator('[aria-label="导入预览"]').innerText()).includes('已与配对原稿'));
  await page.getByRole('button',{name:'确认预览并创建项目'}).click();
  await page.waitForURL(url=>/^\/projects\/[^/]+$/.test(url.pathname)&&!url.pathname.endsWith('/new'));
  const projectUrl=page.url();
  await page.goto(projectUrl+'/source');
  assert((await page.locator('[aria-label="P1 检查与修改结果"]').innerText()).includes('未安排重复'));
  const result=await context.request.get(projectUrl+'/source/download');
  assert.equal((await result.json()).source.text,source);
  await page.screenshot({path:path.join(output,'ui-paired-source.png'),fullPage:true});
  console.log('PASS real browser: external material generation, pasted plan + original pair, create, exact source download, no repeated AI review');
};
