import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildSourceIndex } from './project-foundation-contracts';
import { requireProductionCatalogAuthor, requireProductionCatalog, collectProductionRepairIssues, applyProductionOptimizations, requireProductionOptimization, isProductionCatalog, mergeProductionCatalogs } from './foundation-production-contracts';

const evidence='runtime-3008/live-evidence/2026-09-12T05-05-24-608Z';
const receipt=JSON.parse(readFileSync(`${evidence}/source-receipt.json`,'utf8'));
const findNormalized=(value:any):any=>value?.source?.text&&value?.episodes?value:Object.values(value??{}).filter(v=>v&&typeof v==='object').map(findNormalized).find(Boolean);
const original=findNormalized(receipt);
assert.ok(original,'保存读取凭据含规范化源');
const index=buildSourceIndex(original.episodes.map((e:any)=>({number:e.number,title:e.title,content:e.content})));
const response=(stage:string)=>{const r=JSON.parse(readFileSync(`${evidence}/${stage}-response.json`,'utf8'));return r.data??r.response?.data??JSON.parse(r.rawOutput);};
const before=JSON.parse(readFileSync(`${evidence}/summary.json`,'utf8'));
const catalog=requireProductionCatalogAuthor(response('F2'),index,[1,2]);
assert.ok(isProductionCatalog(catalog));
assert.equal(collectProductionRepairIssues(catalog).length,1);
assert.equal(collectProductionRepairIssues(mergeProductionCatalogs([catalog],index,[1,2])).length,1,'合并不能清除来源核验问题');
assert.equal(catalog.issues[0].sourceRefs[0].episode,1);
const q=requireProductionOptimization(response('Q1'),index,[1,2],catalog.assets);
const final=applyProductionOptimizations(null,catalog,[q],index).f2;
assert.equal(collectProductionRepairIssues(final).length,1,'已保存Q1未修第一集排除声明，不能清除问题');
assert.equal(requireProductionCatalog(final,index,[1,2]).issues.length,1,'读回重算仍阻止就绪');
const input=(content:string)=>buildSourceIndex([{number:1,title:null,content}]);
const wire={format:'ASSET_CATALOG_V2',coverage:[1],assets:[{name:'李四｜默认',type:'CH',episodes:[1],preparation:{mode:'AUDIO'},variants:[]}]};
for(const text of ['他把铜钥匙交给李四。','李四把铜钥匙交还张三。','李四接过铜钥匙。'])assert.equal(requireProductionCatalogAuthor(wire,input(text),[1]).issues.length,1,text);
for(const text of ['他想起李四。','张三：我把铜钥匙交给李四。','他没有把铜钥匙交给李四。','李四VO：记住了。','如果他把铜钥匙交给李四。'])assert.equal(requireProductionCatalogAuthor(wire,input(text),[1]).issues.length,0,text);
const corrected=structuredClone(final);corrected.assets.find(a=>a.name.startsWith('李四'))!.preparation={mode:'UNRESOLVED',note:'第一集交接呈现待核，暂不判定仅声音或身体入镜'};
assert.equal(requireProductionCatalog(corrected,index,[1,2]).issues.length,0,'撤回错误排除后，由既有UNRESOLVED门阻止资料就绪');
console.log(JSON.stringify({savedBefore:{complete:before.complete,documentReady:before.documentReady,issues:before.issues.length},revalidatedAfter:{physicalBlockers:final.issues.length,episode:final.issues[0].sourceRefs[0].episode},modelCalls:0,tests:'passed'}));
